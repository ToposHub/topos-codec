/* 输出端去块滤波（P6 / V7-R4，位流 flags bit2 选载）。
 *
 * spec v2.1（2026-09-22 画质攻坚；编解码两侧一致 = 解码输出即滤波后像素）：
 * - 网格：仅 8×8 变换块边界（TOPOS 变换粒度），垂直/水平两趟独立
 *   （先垂直后水平，光栅序就地更新——与 H.264 环内滤波同序，确定性由
 *   固定遍历序保证）。
 * - 强度：step_px(qp) = max(1, round(scale(qp)·3/173056))（像素域步长
 *   推导：DC 重建步 (scale>>4)/10816 × AC 增益 ~3，见锯齿诊断 §2.2 实测
 *   qp75–86 ↔ 1.3–8.6 LSB 交叉验证）；alpha = clamp(2·step_px, 3, 48)，
 *   beta = alpha/2 + 2。QPT2 细化表流用细化表 scale，与该流反量化步长
 *   同源。
 *   注意"有效域"：scale 每 4 qp 翻倍，故 step_px 直到 qp ≈ 69 都 < 1 →
 *   **qp ≤ 68 一律落到 alpha = 3（clip = 1）**，即图片档（qp 58–63）与
 *   视频中高档拿到的是同一个固定强度；只有低档（netproxy/proxy 的 RC qp
 *   ≥ 70）与 raw16 高档才真正"随 qp 自适应"。实测：把该 floor 抬到 6–20
 *   在 69.5 dB 的图片档上是 −0.38…−8.92 dB 换 ≤0.05 LSB（纯亏），故 floor=3
 *   是选定工作点（docs/image/toos_deblock_verify_2026-09-22.md §1）。
 * - 决策（v2.1 修正符号对称性）：边界段 m0=|p0−q0|、m1=|p1−p0|、
 *   m2=|q1−q0|，当 m0<alpha 且 m1<beta 且 m2<beta 判为块边界（量化台阶）
 *   → 滤波；任一超限即真实边缘/纹理，原样保留（物体轮廓保护）。决策对
 *   台阶方向必须无偏：v2 实现以无符号比较代替取幅值，等价式只在 q0>p0
 *   时成立，反向台阶（实测占帧内台阶能量 53.4%）整片漏滤——v2.1 起两侧
 *   同判。
 * - 滤波 v2：d = clip(±(alpha>>1), (12·(q0−p0) + 4·(p1−q1) + 8) >> 4)，
 *   再以"不得越过 p0/q0 中点"（|d| ≤ |Δ|/2、sign(d)=sign(Δ)）二次收紧。
 *   权重 (12,4) 由两个端点约束联立：平坦邻域纯 DC 台阶（p1−q1 = −Δ）下
 *   d = (W0−W1)·Δ/16，取 W0−W1 = 8 即 d = Δ/2，p0+=d/q0−=d 把台阶整段
 *   抹平（v1 权重 (4,1) 只抹 3Δ/16≈19%，A/B 实测块界台阶仅降 44%）；均匀
 *   斜坡（p1−q1 = −3s，Δ = s）下 (W0−3·W1)/16 = 0 ⇒ 严格零响应。中点界
 *   针对振铃/过冲邻域（p1−q1 与 Δ 同号）——那里权重和可让 d 超过 Δ 把台阶
 *   翻到另一侧，逐帧块效应反而恶化。边缘保护仍由 alpha/beta 门控兜底。
 * - 钳位：结果钳到 [0, 2^bit_depth−1]（v1 无钳位，p0=1023 时 +d 可写出
 *   1023 以上越界样本）。
 * - 并行：整帧解码此前唯一的串行段（4K 1→16 线程只快 2.45×，滤波本身占
 *   4K 20 ms/帧）。两趟按"访问窗口不相交"切片走常驻 tpool —— 垂直趟按行带、
 *   水平趟按边界行区间；两次分发之间即"垂直完成 → 水平开始"的屏障；切片
 *   之间零重叠访问 ⇒ **任意线程数输出逐位一致**（tpool 退化档自动顺序内联）。
 * - 缩放交付（v2.1 新增；预览/代理路径此前**完全不过滤**）：解码器的缩放
 *   交付是"每格取首样本"的整数抽样，源 8×8 块界在目标域落到 8/d 的倍数
 *   上（d = 源/目标抽样比）；DC 台阶幅度不随抽样改变，故同一套 alpha/beta
 *   权重在目标网格上重放（unit = 8/d）。实测 4K→1/2 预览块效应
 *   1.40/1.34 → 0.04/0.17 LSB，PSNR 不降反升。只做 d=2（unit=4）：更小的
 *   抽样比窗口重叠（见 deblock_plane_unit）、1/3 类非整数比网格与相位逐块
 *   漂移，均归后续批次。**注意这不是"源域滤波后抽样"的逐位等价物**——抽样
 *   丢掉的 p0/q1 校正无法在目标域复现，故它是预览级近似（目标图自身的
 *   4 周期网格滤波），交付路径（全尺寸）不受影响。
 * - qp 来源：帧级 qp_base（产品编码器全帧单一 qp，已位流验证；slice 级
 *   delta 的带内细化归后续批次）。alpha 平面（plane 3）不过滤。 */
#ifndef TOPOS_INTERNAL_DEBLOCK_H
#define TOPOS_INTERNAL_DEBLOCK_H

#include <stdint.h>

/* 对单平面就地去块。pix 为行主序 uint16 采样；stride_pix 为行距（采样数）；
 * w/h 为平面几何（8 的倍数，非对齐防御性跳过）；qp 取帧级有效 qp；
 * table_sel 见 quant.h（QPT2 细化表流的滤波强度与其反量化步长同源）；
 * bit_depth 用于输出钳位上界（8..16；域外跳过）。 */
void tc_deblock_plane(uint16_t* pix, int32_t stride_pix, uint32_t w, uint32_t h,
                      uint32_t qp, uint32_t table_sel, uint8_t bit_depth);

/* 缩放交付平面就地去块：unit = 目标域块界周期（1/2 抽样传 4）。w/h 为
 * **目标**平面几何，须为 unit 的倍数（非对齐或 unit<4 跳过）。 */
void tc_deblock_plane_scaled(uint16_t* pix, int32_t stride_pix, uint32_t w,
                             uint32_t h, uint32_t qp, uint32_t table_sel,
                             uint8_t bit_depth, uint32_t unit);

#endif /* TOPOS_INTERNAL_DEBLOCK_H */
